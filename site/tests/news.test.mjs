import assert from 'node:assert/strict';
import {newsRoute,signedSession,sessionValid,validUpload} from '../worker/news.mjs';
const secret='test-key'; const now=Date.now();
const token=await signedSession(secret,now+10000);
assert(await sessionValid('news_session='+token,secret,now));
assert(!await sessionValid('news_session='+token,'wrong',now));
assert(!await sessionValid('news_session='+token,secret,now+20000));
assert(!await sessionValid('news_session='+token.slice(0,-1)+'z',secret,now));
const proof='ab'.repeat(32);
const verifier=Buffer.from(await crypto.subtle.digest('SHA-256',Buffer.from(proof,'hex'))).toString('hex');
const env={NEWS_AUTH:JSON.stringify({salt:'ab'.repeat(16),iterations:600000,verifier}),NEWS_SESSION_KEY:secret,NEWS_UPLOAD_TOKEN:'upload',DB:{prepare(){return {bind(){return this;},async first(){return {count:1};}}}}};
assert.equal((await newsRoute(new Request('https://example.com/news/api/dashboard'),env)).status,401);
assert.equal(await newsRoute(new Request('https://example.com/api/snapshot'),env),null);
assert.equal((await newsRoute(new Request('https://example.com/news/api/upload',{method:'POST',body:'{}'}),env)).status,401);
assert.equal((await newsRoute(new Request('https://example.com/news/login',{method:'POST',body:JSON.stringify({proof})}),env)).status,403);
const response=await newsRoute(new Request('https://example.com/news/login',{method:'POST',headers:{origin:'https://example.com'},body:JSON.stringify({proof})}),env);
assert.equal(response.status,200);assert(response.headers.get('set-cookie').includes('HttpOnly'));
const invalid=await newsRoute(new Request('https://example.com/news/login',{method:'POST',headers:{origin:'https://example.com'},body:JSON.stringify({proof:'cd'.repeat(32)})}),env);
assert.equal(invalid.status,401);
assert(!validUpload({generated_at:'invalid',snapshots:[]}));
assert(validUpload({generated_at:'2026-09-10T09:00:00.000000+00:00',snapshots:[0,24,72,168,720].map(hours=>({hours,body:'YWJj'}))}));
assert(!validUpload({generated_at:'2026-09-10T09:00:00.000000+00:00',snapshots:Array(5).fill({hours:24,body:'YWJj'})}));
console.log('News route auth, origin, session expiry, upload validation and isolation passed. No network.');
