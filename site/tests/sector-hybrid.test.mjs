import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
import {isHybridSnapshot,HYBRID_SERIES} from '../lib/sector-hybrid.ts';
import {ROTATION_SECTORS} from '../lib/rotation-entry.ts';
import {renderToStaticMarkup} from 'react-dom/server';
import React from 'react';
const row=ticker=>({ticker,sector:ticker,status:'READY',direction:'OUT',model:'PRICE_EXTRA',signal:'NONE',score:.4,threshold:.6});
const s={series_version:HYBRID_SERIES,as_of:'2026-09-21',decision_date:'2026-09-18',latest_price_date:'2026-09-21',status:'READY',rows:ROTATION_SECTORS.map(row)};
assert.ok(isHybridSnapshot(s));
assert.ok(!isHybridSnapshot({...s,decision_date:'2026-09-25'}));
assert.ok(!isHybridSnapshot({...s,as_of:'2026-10-10'}));
assert.ok(!isHybridSnapshot({...s,rows:[s.rows[0],...s.rows.slice(0,10)]}));
assert.ok(!isHybridSnapshot({...s,rows:s.rows.map(r=>({...r,signal:'OUT'}))}));
assert.ok(isHybridSnapshot({...s,status:'ERROR',rows:[]}));
const source=readFileSync(new URL('../app/SectorHybridPanel.tsx',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{jsx:ts.JsxEmit.React,module:ts.ModuleKind.ESNext}}).outputText;
globalThis.React=React;
const {default:Panel}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const html=renderToStaticMarkup(React.createElement(Panel,{snapshot:s,date:s.as_of}));
assert.match(html,/이번 판단주 신호 없음/);
assert.match(html,/전환 확률이 아닙니다/);
assert.equal((html.match(/scope="row"/g)||[]).length,11);
assert.match(renderToStaticMarkup(React.createElement(Panel,{snapshot:s,date:'2026-09-01'})),/확인할 수 없습니다/);
const dashboard=readFileSync(new URL('../app/DashboardApp.tsx',import.meta.url),'utf8');
assert.ok(dashboard.indexOf('<SectorHybridPanel')<dashboard.indexOf('id="research-reference"'));
assert.ok(dashboard.indexOf('<RotationEntryPanel')>dashboard.indexOf('id="research-reference"'));
console.log('Hybrid contract, temporal guards, 11-row render and section placement passed.');
